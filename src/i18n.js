function i18nNormalizeLanguage(value) {
  return typeof value === 'string' && /^en(?:[-_]|$)/i.test(value) ? 'en' : 'zh-CN';
}

function i18nInitialLanguage() {
  try {
    const query = new URLSearchParams(location.search).get('lang');
    if (query && /^(?:en(?:[-_][a-z]+)?|zh(?:[-_](?:cn|hans))?)$/i.test(query)) return i18nNormalizeLanguage(query);
  } catch {}
  try {
    const saved = localStorage.getItem('tide-language');
    if (saved) return i18nNormalizeLanguage(saved);
  } catch {}
  return 'en';
}

let i18nLanguage = i18nInitialLanguage();

export function getLanguage() {
  return i18nLanguage;
}

export function setLanguage(next) {
  i18nLanguage = i18nNormalizeLanguage(next);
  try { localStorage.setItem('tide-language', i18nLanguage); } catch {}
  return i18nLanguage;
}

