import assert from 'node:assert/strict';
import {Game,V} from '../src/game.js';
const notices=[];
const g=new Game(()=>{},text=>notices.push(text));
g.phase=3;g.player=V(-6.5,3,-18);g.hasRecorder=true;
g.act('pump-listen');
assert(!g.observations.pumpConfirmed,'pressing a button cannot claim the creature has arrived');
assert(notices.at(-1).includes('是否朝声音转向'));
for(let n=0;n<240;n++)g.tick(1/60);
assert(g.observations.pumpConfirmed,'real pursuit reaching pump confirms rule from dry overlook');
const count=notices.filter(s=>s.includes('水纹停在了')).length;
for(let n=0;n<600;n++)g.tick(1/60);
assert.equal(notices.filter(s=>s.includes('水纹停在了')).length,count,'observation is not spammed');
const h=new Game();h.phase=3;h.player=V(-6.5,3,-18);h.act('pump-listen');h.sourceAt=100;
h.sound('knock',V(-8,0,-30),20,true);
for(let n=0;n<180;n++)h.tick(1/60);
assert(!h.observations.pumpConfirmed,'a competing real lure cannot trigger fictional pump confirmation');
const k=new Game();k.phase=3;k.player=V(-8,0,-30);k.act('pump-listen');
for(let n=0;n<240;n++)k.tick(1/60);
assert(!k.observations.pumpConfirmed,'no narrated visual observation from lower remote position');
g.reset();assert.deepEqual(g.observations,{});
console.log('PASS observed sound rule: actual pursuit, visible safe overlook, competing lure, one-shot and reset');
